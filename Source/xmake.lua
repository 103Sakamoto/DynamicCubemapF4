set_xmakever("3.0.0")
set_project("DynamicCubemapF4")
set_version("1.3.1")
set_languages("c++23")
set_arch("x64")
add_rules("mode.debug", "mode.releasedbg")
set_runtimes("MD")

option("detours_root")
    set_showmenu(true)
    set_description("vcpkg installed/x64-windows-static-md directory containing include/detours/detours.h and lib/detours.lib")
option_end()

includes("lib/CommonLibF4")

target("DynamicCubemapF4")
    set_kind("shared")
    set_default(true)
    set_license("GPL-3.0-only")
    add_deps("commonlibf4")
    add_files("src/Main.cpp")
    add_includedirs("src")
    set_pcxxheader("src/PCH.hpp")
    add_defines("WIN32_LEAN_AND_MEAN", "NOMINMAX")
    add_syslinks("d3d11", "d3dcompiler", "dxgi", "user32")
    on_load(function(target)
        local root = get_config("detours_root")
        assert(root, "Set --detours_root=E:/Coding/F4/vcpkg/installed/x64-windows-static-md")
        assert(os.isfile(path.join(root, "include/detours/detours.h")), "Detours header not found")
        assert(os.isfile(path.join(root, "lib/detours.lib")), "Detours library not found")
        target:add("includedirs", path.join(root, "include"))
        target:add("linkdirs", path.join(root, "lib"))
        target:add("links", "detours")
    end)
target_end()
